import { randomInt } from 'node:crypto';
import { expect, Locator, test } from '@playwright/test';

test('booking uses the real API, preserves details on conflict and confirms another slot', async ({ page }) => {
  test.skip(process.env['E2E_REAL_AUTH'] !== '1', 'Requires the isolated API and database.');
  await page.setViewportSize({ width: 320, height: 720 });
  await page.goto('/login');
  await page.getByLabel('Номер телефону').fill(process.env['E2E_ADMIN_PHONE']!);
  await page.getByLabel('Пароль', { exact: true }).fill(process.env['E2E_ADMIN_PASSWORD']!);
  await page.getByRole('button', { name: 'Увійти' }).click();
  await expect(page).toHaveURL(/\/admin$/);
  const scheduleStatus = await page.evaluate(async () => {
    const schedule = await (await fetch('/api/admin/inspection-schedule')).json();
    await fetch('/api/auth/antiforgery');
    const token = decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]);
    const intervals = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'].map(dayOfWeek => ({ dayOfWeek, start: '09:00', end: '10:00' }));
    return (await fetch('/api/admin/inspection-schedule', { method: 'PUT', headers: { 'Content-Type': 'application/json', RequestVerificationToken: token }, body: JSON.stringify({ version: schedule.version, intervals }) })).status;
  });
  expect(scheduleStatus).toBe(204);
  await page.goto('/account/book');
  await page.getByLabel('Дата', { exact: true }).fill('2099-01-15');
  await page.getByLabel('09:00', { exact: true }).check();
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByLabel('VIN').fill('1HGCM82633A004352');
  await page.getByLabel('Марка').fill('Test'); await page.getByLabel('Модель').fill('Model');
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByLabel('Що потрібно оглянути?').fill('Тестовий опис');
  await page.getByRole('button', { name: 'Далі' }).click();
  const taken = await page.evaluate(async () => {
    const slots = await (await fetch('/api/inspection-slots?date=2099-01-15')).json();
    await fetch('/api/auth/antiforgery');
    const token = decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]);
    return (await fetch('/api/appointments', { method: 'POST', headers: { 'Content-Type': 'application/json', RequestVerificationToken: token }, body: JSON.stringify({ inspectionStartUtc: slots.slots[0].startUtc, vin: '1HGCM82633A004352', make: 'Test', model: 'Model', problemDescription: 'Issue' }) })).status;
  });
  expect(taken).toBe(201);
  await page.getByRole('button', { name: 'Підтвердити запис' }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Цей час уже недоступний' })).toBeVisible();
  await page.getByLabel('09:30', { exact: true }).check();
  await page.getByRole('button', { name: 'Далі' }).click();
  await expect(page.getByLabel('VIN')).toHaveValue('1HGCM82633A004352');
  await page.getByRole('button', { name: 'Далі' }).click();
  await expect(page.getByLabel('Що потрібно оглянути?')).toHaveValue('Тестовий опис');
  await page.getByRole('button', { name: 'Далі' }).click();
  const created = page.waitForResponse(r => r.url().endsWith('/api/appointments') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Підтвердити запис' }).click();
  expect((await created).status()).toBe(201);
  await expect(page).toHaveURL(/\/account\/book\/success$/);
  await expect(page.getByRole('heading', { name: 'Запис підтверджено' })).toBeVisible();
  await expect(page.getByText(/09:30/)).toBeVisible();
  await expect(page.getByRole('link', { name: process.env['E2E_TEST_CONTACT_PHONE']! })).toBeVisible();
  await page.getByRole('link', { name: 'Переглянути ціни' }).click();
  await expect(page).toHaveURL(/#prices$/); await expect(page.locator('#prices')).toBeVisible();
  await expect(page.locator('#prices')).toBeInViewport();
  await page.goBack(); await expect(page).toHaveURL(/\/account\/book\/success$/);
  await page.getByRole('link', { name: 'Контакти', exact: true }).click();
  await expect(page).toHaveURL(/#contacts$/); await expect(page.locator('#contacts')).toBeInViewport();
  await page.goBack(); await expect(page).toHaveURL(/\/account\/book\/success$/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('link', { name: 'Мої записи' }).last().click();
  await expect(page).toHaveURL(/\/account\/appointments$/);
  await expect(page.getByText('*************4352').first()).toBeVisible();
  await expect(page.getByText('Очікує огляду').first()).toBeVisible();
  const adminOrder = await page.getByRole('link', { name: /Деталі запису/ }).first().getAttribute('href');
  await page.getByRole('link', { name: /Деталі запису/ }).first().click();
  await expect(page.getByText('1HGCM82633A004352')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Історія статусів' })).toBeVisible();
  await page.goto('/admin/inspection-calendar');
  await page.getByLabel('Дата огляду').fill('2099-01-15'); await page.getByRole('button', { name: 'Показати дату' }).click();
  await expect(page.getByText('E2E test').first()).toBeVisible();
  await expect(page.getByText(/Зайнято/).first()).toBeVisible();
  await page.getByRole('button', { name: 'Налаштування графіка' }).click();
  await page.getByLabel('Правило дня').selectOption('Closed');
  await page.getByRole('button', { name: 'Зберегти виняток' }).click();
  await expect(page.getByRole('dialog')).toContainText('Зміна вплине на такі записи');
  await expect(page.getByRole('dialog')).toContainText('E2E test');
  await page.getByRole('dialog').getByRole('button', { name: 'Зберегти' }).click();
  await expect(page.getByText('Зміни збережено. Наявні записи збережено.')).toBeVisible();
  await page.getByRole('button', { name: 'Записи на огляд' }).click();
  await expect(page.getByText('E2E test').first()).toBeVisible();
  await page.getByRole('link', { name: 'Відкрити замовлення' }).first().click();
  await expect(page.getByRole('heading', { name: 'Огляд і клієнт' })).toBeVisible();
  await page.goto('/admin');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Вийти' }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.goto('/register');
  const phone = '000' + String(randomInt(10_000_000)).padStart(7, '0');
  await page.getByLabel('Ім’я').fill('Тестовий клієнт'); await page.getByLabel('Номер телефону').fill(phone);
  await page.getByLabel('Пароль', { exact: true }).fill('Example-password-123!');
  await page.getByLabel('Повторіть пароль').fill('Example-password-123!');
  await page.getByRole('button', { name: 'Зареєструватися' }).click();
  await expect(page).toHaveURL(/\/account\/appointments$/);
  await expect(page.getByText('Записів не знайдено')).toBeVisible();
  await page.goto(adminOrder!);
  await expect(page.getByRole('heading', { name: 'Запис не знайдено' })).toBeVisible();
  await page.getByRole('link', { name: 'Мої записи' }).first().click();
  await page.getByRole('link', { name: 'Записатися на огляд' }).first().click();
  await page.getByLabel('Дата', { exact: true }).fill('2099-01-16');
  await page.getByLabel('09:00', { exact: true }).check();
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByLabel('VIN').fill('1HGCM82633A004352');
  await page.getByLabel('Марка').fill('Клієнт'); await page.getByLabel('Модель').fill('Авто');
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByLabel('Що потрібно оглянути?').fill('Дивіться відео: https://example.invalid/video.mp4');
  await page.getByRole('button', { name: 'Далі' }).click();
  await expect(page.getByText(/Опишіть проблему автомобіля словами/)).toBeVisible();
  await page.getByLabel('Що потрібно оглянути?').fill('!!!');
  await page.getByRole('button', { name: 'Далі' }).click();
  await expect(page.getByText(/Лише символів або посилання недостатньо/)).toBeVisible();
  await page.getByLabel('Що потрібно оглянути?').fill('Опис для огляду');
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByRole('button', { name: 'Підтвердити запис' }).click();
  await expect(page).toHaveURL(/\/account\/book\/success$/);
  await page.getByRole('link', { name: 'Мої записи' }).last().click();
  await expect(page.getByRole('heading', { name: 'Клієнт Авто' })).toBeVisible();
  const menu = page.getByLabel('Дії із записом');
  await expect(menu).toBeVisible();
  await menu.scrollIntoViewIfNeeded();
  // Viewport coordinates move when a mobile browser scrolls the opened menu into view.
  // Document coordinates still detect a real layout shift of either element.
  const documentBox = (locator: Locator) => locator.evaluate(element => {
    const rect = element.getBoundingClientRect();
    return { x: rect.x + window.scrollX, y: rect.y + window.scrollY, width: rect.width, height: rect.height };
  });
  const beforeMenu = await documentBox(menu);
  const beforeCard = await documentBox(page.locator('.card'));
  await menu.click();
  await expect(page.getByRole('button', { name: 'Скасувати запис' })).toBeVisible();
  expect(await documentBox(menu)).toEqual(beforeMenu);
  expect(await documentBox(page.locator('.card'))).toEqual(beforeCard);
  await menu.click();
  await expect(page.getByText('*************4352', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Завершені' }).click();
  await expect(page.getByText('Записів не знайдено')).toBeVisible();
  await page.getByRole('button', { name: 'Активні' }).click();
  await page.getByRole('link', { name: /Деталі запису/ }).click();
  await expect(page.getByText('Опис для огляду')).toBeVisible();
  await expect(page.getByText('1HGCM82633A004352')).toBeVisible();
  const heading = await page.getByRole('heading', { name: 'Клієнт Авто' }).boundingBox();
  const detailMenu = await page.getByLabel('Дії із записом').boundingBox();
  expect(detailMenu!.x).toBeGreaterThan(heading!.x + heading!.width);
  expect(Math.abs(detailMenu!.y + detailMenu!.height / 2 - (heading!.y + heading!.height / 2))).toBeLessThan(2);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);

  await page.getByLabel('Дії із записом').click();
  await page.getByRole('button', { name: 'Скасувати запис' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  const cancellation = page.waitForResponse(r => /\/api\/appointments\/[^/]+\/cancel$/.test(r.url()) && r.request().method() === 'POST');
  const updated = page.waitForResponse(r => /\/api\/appointments\/[^/]+$/.test(r.url()) && r.request().method() === 'GET');
  await page.getByRole('button', { name: 'Підтвердити', exact: true }).click();
  expect((await cancellation).status()).toBe(204); expect((await updated).status()).toBe(200);
  await expect(page.getByText('Запис скасовано.')).toBeVisible();
  await expect(page.getByText('Скасовано', { exact: true }).first()).toBeVisible();
  await expect(page.getByLabel('Дії із записом')).toHaveCount(0);
  await page.getByRole('link', { name: 'Запис на огляд' }).click();
  await page.getByLabel('Дата', { exact: true }).fill('2099-01-16');
  await page.getByLabel('09:00', { exact: true }).check();
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByLabel('VIN').fill('1HGCM82633A004352');
  await page.getByLabel('Марка').fill('Клієнт'); await page.getByLabel('Модель').fill('Авто');
  await page.getByRole('button', { name: 'Далі' }).click();
  await page.getByLabel('Що потрібно оглянути?').fill('Повторний запис');
  await page.getByRole('button', { name: 'Далі' }).click();
  const rebooked = page.waitForResponse(r => r.url().endsWith('/api/appointments') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Підтвердити запис' }).click();
  expect((await rebooked).status()).toBe(201);
  await expect(page).toHaveURL(/\/account\/book\/success$/);
  await expect(page.getByText(/09:00/)).toBeVisible();

});
