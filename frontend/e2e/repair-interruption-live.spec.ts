import { expect, test } from '@playwright/test';
import { login } from './admin-users-helpers';

test('pause offers, refusal, concurrent acceptance and overdue return remain visible', async ({ page }) => {
  test.skip(process.env['E2E_LIVE_API'] !== '1', 'Requires isolated API and PostgreSQL.');
  test.setTimeout(120_000);
  await page.setViewportSize({ width: 375, height: 800 });
  await login(page, process.env['E2E_ADMIN_PHONE']!, process.env['E2E_ADMIN_PASSWORD']!);
  await expect(page).toHaveURL(/\/admin$/);
  const setup = await page.evaluate(async () => {
    await fetch('/api/auth/antiforgery');
    const headers = () => ({ 'Content-Type': 'application/json', RequestVerificationToken: decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]) });
    const check = async (response: Response, expected: number) => { if (response.status !== expected) throw new Error(`${response.url}: ${response.status}`); return response; };
    await check(await fetch('/api/admin/repair-capacity', { method: 'PUT', headers: headers(), body: JSON.stringify({ workplaces: 1 }) }), 204);
    const schedule = await (await check(await fetch('/api/admin/inspection-schedule'), 200)).json();
    const intervals = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'].map(dayOfWeek => ({ dayOfWeek, start: '09:00', end: '12:00' }));
    const preview = await (await check(await fetch('/api/admin/inspection-schedule/preview', { method: 'POST', headers: headers(), body: JSON.stringify({ version: schedule.version, intervals }) }), 200)).json();
    await check(await fetch('/api/admin/inspection-schedule', { method: 'PUT', headers: headers(), body: JSON.stringify({ version: schedule.version, intervals, confirmationToken: preview.confirmationToken }) }), 204);
    const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Kyiv', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
    const plus = (days: number) => { const value = new Date(`${today}T12:00:00Z`); value.setUTCDate(value.getUTCDate() + days); return value.toISOString().slice(0, 10); };
    const slots = (await (await check(await fetch(`/api/inspection-slots?date=${plus(1)}`), 200)).json()).slots;
    const ids: string[] = [];
    for (const [index, model, start, durationDays] of [[0, 'Пауза', 0, 3], [1, 'Довгий', 20, 12], [2, 'Перший', 40, 8], [3, 'Другий', 60, 7]] as const) {
      const guest = model === 'Другий';
      const order = await (await check(await fetch(guest ? '/api/admin/appointments/guest' : '/api/appointments', { method: 'POST', headers: headers(), body: JSON.stringify({ inspectionStartUtc: slots[index].startUtc, make: 'Тест', model, problemDescription: 'Опис', ...(guest ? { customerName: 'Клієнт без акаунта', customerPhone: '+380000000001' } : {}) }) }), 201)).json();
      const details = await (await check(await fetch(`/api/appointments/${order.id}`), 200)).json();
      await check(await fetch(`/api/admin/appointments/${order.id}/schedule`, { method: 'POST', headers: headers(), body: JSON.stringify({ version: details.version, start: plus(start), durationDays, price: 100, inspectionPerformed: true }) }), 204);
      ids.push(order.id);
    }
    const source = await (await check(await fetch(`/api/appointments/${ids[0]}`), 200)).json();
    await check(await fetch(`/api/admin/appointments/${ids[0]}/transition`, { method: 'POST', headers: headers(), body: JSON.stringify({ version: source.version, target: 'InProgress' }) }), 204);
    return { ids, today, delayEnd: plus(12), firstStart: plus(40) };
  });
  await page.goto(`/admin/appointments/${setup.ids[0]}`);
  await page.getByRole('button', { name: 'Призупинити', exact: true }).click();
  await page.getByLabel('Причина паузи').fill('Очікування деталей');
  await page.getByLabel('Орієнтовна тривалість, календарних днів').fill('10');
  await page.getByLabel('Автомобіль прибрано з робочого місця').check();
  await page.getByRole('button', { name: 'Підтвердити паузу' }).click();
  await expect(page.getByText('Призупинено', { exact: true }).first()).toBeVisible();
  const offer = page.locator('app-repair-offer');
  await expect(offer).toContainText('Перший');
  await expect(offer).not.toContainText('Довгий');
  await offer.getByRole('button', { name: 'Зв’язатися з клієнтом' }).focus();
  await page.keyboard.press('Enter');
  await expect(offer.getByRole('dialog', { name: 'Зв’язатися з клієнтом' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(offer.getByRole('dialog', { name: 'Зв’язатися з клієнтом' })).not.toBeVisible();
  await offer.getByRole('button', { name: 'Клієнт погодився' }).click();
  await offer.getByRole('dialog', { name: 'Підтвердити погоджену дату?' }).getByRole('button', { name: 'Скасувати' }).click();
  await expect(offer).toContainText('Перший');
  await offer.getByRole('button', { name: 'Клієнт відмовився' }).click();
  await expect(offer).toContainText('Другий'); await expect(offer).toContainText('Клієнт без акаунта');
  const concurrent = await page.evaluate(async ({ source, candidate }) => {
    const headers = () => ({ 'Content-Type': 'application/json', RequestVerificationToken: decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]) });
    const pause = (await (await fetch(`/api/appointments/${source}`)).json()).activePause;
    const order = await (await fetch(`/api/appointments/${candidate}`)).json();
    const body = JSON.stringify({ version: order.version, pauseId: pause.id, customerAgreed: true });
    const results = await Promise.all([0, 1].map(() => fetch(`/api/admin/repair-planning/${candidate}/accept-earlier`, { method: 'POST', headers: headers(), body })));
    return results.map(r => r.status).sort();
  }, { source: setup.ids[0], candidate: setup.ids[3] });
  expect(concurrent).toEqual([204, 409]);
  await page.reload(); await expect(page.locator('app-repair-offer')).toContainText('Підходящих ремонтів');
  const result = await page.evaluate(async ({ ids, delayEnd }) => {
    const headers = () => ({ 'Content-Type': 'application/json', RequestVerificationToken: decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]) });
    const details = async (id: string) => (await (await fetch(`/api/appointments/${id}`)).json());
    const candidate = await details(ids[3]);
    const start = await fetch(`/api/admin/appointments/${ids[3]}/transition`, { method: 'POST', headers: headers(), body: JSON.stringify({ version: candidate.version, target: 'InProgress' }) });
    if (start.status !== 204) throw new Error(`Start: ${start.status}`);
    const paused = await details(ids[0]);
    const blocked = await fetch(`/api/admin/appointments/${ids[0]}/resume`, { method: 'POST', headers: headers(), body: JSON.stringify({ version: paused.version }) });
    const preview = await (await fetch(`/api/admin/repair-planning/${ids[3]}/delay-preview?finish=${delayEnd}`)).json();
    const active = await details(ids[3]);
    await fetch('/api/admin/repair-capacity', { method: 'PUT', headers: headers(), body: JSON.stringify({ workplaces: 2 }) });
    const old = await fetch(`/api/admin/repair-planning/${ids[3]}/delay`, { method: 'POST', headers: headers(), body: JSON.stringify({ version: active.version, finish: delayEnd, confirmationToken: preview.confirmationToken, confirmed: true }) });
    await fetch('/api/admin/repair-capacity', { method: 'PUT', headers: headers(), body: JSON.stringify({ workplaces: 1 }) });
    const refreshed = await (await fetch(`/api/admin/repair-planning/${ids[3]}/delay-preview?finish=${delayEnd}`)).json();
    const saved = await fetch(`/api/admin/repair-planning/${ids[3]}/delay`, { method: 'POST', headers: headers(), body: JSON.stringify({ version: active.version, finish: delayEnd, confirmationToken: refreshed.confirmationToken, confirmed: true }) });
    return { blocked: blocked.status, stale: old.status, saved: saved.status, conflicts: refreshed.conflicts.map((c: { id: string }) => c.id), paused: await details(ids[0]), first: await details(ids[2]) };
  }, { ids: setup.ids, delayEnd: setup.delayEnd });
  expect(result.blocked).toBe(409); expect(result.stale).toBe(409); expect(result.saved).toBe(204);
  expect(result.conflicts).toContain(setup.ids[0]); expect(result.paused.dateConflict).toBe(true);
  const originalStart = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Kyiv', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(result.first.repairPlan.plannedStartUtc));
  expect(originalStart).toBe(setup.firstStart);
  await page.reload(); await expect(page.getByText('Конфлікт дати', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.setViewportSize({ width: 1440, height: 900 });
  await expect(page.getByText('Конфлікт дати', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
