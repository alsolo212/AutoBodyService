import { execFileSync } from 'node:child_process';
import { expect, test } from '@playwright/test';
import { login, register } from './admin-users-helpers';

test('calendar saves weekly hours and a date exception without removing a conflicting booking', async ({ page, browser }) => {
  test.skip(process.env['E2E_LIVE_API'] !== '1', 'Requires isolated API and PostgreSQL.');
  test.setTimeout(90_000);
  const container = process.env['PROFILE_VERIFY_CONTAINER'] ?? '';
  if (!/^autobody-ui-verify-[a-f0-9]+$/.test(container)) throw new Error('Expected disposable E2E database');
  const label = execFileSync('docker', ['inspect', '-f', '{{ index .Config.Labels "autobody.auth-e2e.disposable" }}', container], { encoding: 'utf8' }).trim();
  if (label !== 'true') throw new Error('Database is not marked disposable');
  const sql = (query: string) => execFileSync('docker', ['exec', container, 'psql', '-U', 'auth_test', '-d', 'auth_test', '-v', 'ON_ERROR_STOP=1', '-At', '-c', query], { encoding: 'utf8' }).trim();
  await login(page, process.env['E2E_ADMIN_PHONE']!, process.env['E2E_ADMIN_PASSWORD']!);
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto('/admin/inspection-calendar');
  await page.getByLabel('Дата огляду').fill('2099-09-10');
  await page.getByRole('button', { name: 'Показати дату' }).click();
  await expect(page.getByRole('heading', { name: /Час для огляду/ })).toBeVisible();
  await page.getByRole('button', { name: 'Налаштування графіка' }).click();
  await expect(page.getByRole('heading', { name: 'Робочі дні та години' })).toBeVisible();
  await page.locator('.day-row').filter({ hasText: 'Четвер' }).getByRole('button', { name: '+ Додати час' }).click();
  await page.getByLabel('Четвер, початок').fill('09:00');
  await page.getByLabel('Четвер, кінець').fill('11:00');
  await page.getByRole('button', { name: 'Зберегти тижневий графік' }).click();
  let dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('Зачеплених майбутніх записів немає');
  let saved = page.waitForResponse(r => r.url().endsWith('/api/admin/inspection-schedule') && r.request().method() === 'PUT');
  await dialog.getByRole('button', { name: 'Зберегти' }).click();
  expect((await saved).status()).toBe(204);
  await expect(page.getByRole('status').filter({ hasText: 'Наявні записи збережено' })).toBeVisible();
  expect(sql(`SELECT count(*) FROM "InspectionWeeklyHours" WHERE "DayOfWeek" = 4 AND "Start" = '09:00' AND "End" = '11:00'`)).toBe('1');
  const id = await page.evaluate(async () => {
    const slots = await (await fetch('/api/inspection-slots?date=2099-09-10')).json();
    await fetch('/api/auth/antiforgery');
    const token = decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]);
    const response = await fetch('/api/appointments', { method: 'POST', headers: { 'Content-Type': 'application/json', RequestVerificationToken: token }, body: JSON.stringify({ inspectionStartUtc: slots.slots[0].startUtc, vin: '1HGCM82633A123456', make: 'Календар', model: 'Тест', problemDescription: 'Пошкоджено бампер' }) });
    if (response.status !== 201) throw new Error(`Booking failed: ${response.status}`);
    return (await response.json()).id as string;
  });
  expect(id).toMatch(/^[a-f0-9-]{36}$/i);
  await page.getByRole('button', { name: 'Записи на огляд' }).click();
  await page.getByRole('button', { name: 'Показати дату' }).click();
  await expect(page.getByRole('list', { name: 'Записи на огляд' })).toContainText('Календар Тест');
  await page.getByRole('button', { name: 'Налаштування графіка' }).click();
  await page.getByLabel('Четвер, початок').fill('10:00');
  await page.getByRole('button', { name: 'Зберегти тижневий графік' }).click();
  dialog = page.getByRole('dialog');
  await expect(dialog).toContainText('Зміна вплине на такі записи');
  await expect(dialog).toContainText('Календар Тест');
  saved = page.waitForResponse(r => r.url().endsWith('/api/admin/inspection-schedule') && r.request().method() === 'PUT');
  await dialog.getByRole('button', { name: 'Зберегти' }).click();
  expect((await saved).status()).toBe(204);
  await expect(page.getByRole('status').filter({ hasText: 'Наявні записи збережено' })).toBeVisible();
  expect(sql(`SELECT count(*) FROM "InspectionWeeklyHours" WHERE "DayOfWeek" = 4 AND "Start" = '10:00' AND "End" = '11:00'`)).toBe('1');
  expect(sql(`SELECT "Status" FROM "Appointments" WHERE "Id" = '${id}'`)).toBe('0');
  await page.getByLabel('Правило дня').selectOption('Replace');
  await page.getByRole('button', { name: '+ Додати інтервал' }).click();
  await page.getByLabel('Початок інтервалу 1').fill('09:00');
  await page.getByLabel('Кінець інтервалу 1').fill('10:00');
  await page.getByLabel('Причина (необов’язково)').fill('Тестовий графік');
  await page.getByRole('button', { name: 'Зберегти виняток' }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  const exception = page.waitForResponse(r => r.url().endsWith('/api/admin/inspection-exceptions') && r.request().method() === 'PUT');
  await page.getByRole('dialog').getByRole('button', { name: 'Зберегти' }).click();
  expect((await exception).status()).toBe(200);
  await expect(page.getByRole('status').filter({ hasText: 'Наявні записи збережено' })).toBeVisible();
  expect(sql(`SELECT count(*) FROM "InspectionDateOverrides" o JOIN "InspectionDateInterval" i ON i."OverrideId" = o."Id" WHERE o."Date" = '2099-09-10' AND o."Mode" = 2 AND i."Start" = '09:00' AND i."End" = '10:00'`)).toBe('1');
  await page.getByRole('button', { name: 'Записи на огляд' }).click();
  await expect(page.getByRole('list', { name: 'Записи на огляд' })).toContainText('Календар Тест');
  await expect(page.getByRole('list', { name: 'Вільний час' })).not.toContainText('09:00');
  const currentVersion = await page.evaluate(async () => (await (await fetch('/api/admin/inspection-schedule')).json()).version as string);
  const user = await register(browser, 'Клієнт календаря', '0000000079');
  try {
    const denied = await user.page.evaluate(async version => {
      await fetch('/api/auth/antiforgery');
      const token = decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]);
      const get = await fetch('/api/admin/inspection-schedule');
      const update = await fetch('/api/admin/inspection-schedule', { method: 'PUT', headers: { 'Content-Type': 'application/json', RequestVerificationToken: token }, body: JSON.stringify({ version, intervals: [] }) });
      return [get.status, update.status];
    }, currentVersion);
    expect(denied).toEqual([403, 403]);
    expect(sql(`SELECT count(*) FROM "InspectionWeeklyHours" WHERE "DayOfWeek" = 4 AND "Start" = '10:00' AND "End" = '11:00'`)).toBe('1');
    expect(sql(`SELECT "Status" FROM "Appointments" WHERE "Id" = '${id}'`)).toBe('0');
  } finally { await user.context.close(); }
});
