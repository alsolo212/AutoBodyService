import { expect, test } from '@playwright/test';
import { login } from './admin-users-helpers';

test('workplaces and one-step repair planning work on mobile and desktop', async ({ page }) => {
  test.skip(process.env['E2E_LIVE_API'] !== '1', 'Requires isolated API and PostgreSQL.');
  await page.setViewportSize({ width: 320, height: 800 });
  await login(page, process.env['E2E_ADMIN_PHONE']!, process.env['E2E_ADMIN_PASSWORD']!);
  await expect(page).toHaveURL(/\/admin$/);
  await page.goto('/admin/inspection-calendar');
  await page.getByRole('button', { name: 'Налаштування графіка' }).click();
  await expect(page.getByLabel('Кількість робочих місць')).toBeVisible();
  await page.getByLabel('Кількість робочих місць').fill('2');
  await page.getByRole('button', { name: 'Зберегти кількість місць' }).click();
  await expect(page.getByText('Кількість робочих місць збережено.')).toBeVisible();
  const id = await page.evaluate(async () => {
    const headers = () => ({ 'Content-Type': 'application/json', RequestVerificationToken: decodeURIComponent(document.cookie.split('; ').find(c => c.startsWith('XSRF-TOKEN='))!.split('=')[1]) });
    await fetch('/api/auth/antiforgery');
    const schedule = await (await fetch('/api/admin/inspection-schedule')).json();
    const intervals = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'].map(dayOfWeek => ({ dayOfWeek, start: '09:00', end: '10:00' }));
    const preview = await (await fetch('/api/admin/inspection-schedule/preview', { method: 'POST', headers: headers(), body: JSON.stringify({ version: schedule.version, intervals }) })).json();
    const updated = await fetch('/api/admin/inspection-schedule', { method: 'PUT', headers: headers(), body: JSON.stringify({ version: schedule.version, intervals, confirmationToken: preview.confirmationToken }) });
    if (updated.status !== 204) throw new Error(`Schedule update: ${updated.status}`);
    const today = new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Kyiv', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date());
    const tomorrow = new Date(`${today}T12:00:00Z`); tomorrow.setUTCDate(tomorrow.getUTCDate() + 1);
    const date = tomorrow.toISOString().slice(0, 10);
    const slots = await (await fetch(`/api/inspection-slots?date=${date}`)).json();
    const result = await fetch('/api/admin/appointments/guest', { method: 'POST', headers: headers(), body: JSON.stringify({ customerName: 'Тестовий клієнт', customerPhone: '+380000000001', inspectionStartUtc: slots.slots[0].startUtc, make: 'Тестове', model: 'Авто', problemDescription: 'Тестове пошкодження' }) });
    if (result.status !== 201) throw new Error(`Guest booking: ${result.status}`);
    return (await result.json()).id as string;
  });
  await page.goto(`/admin/appointments/${id}`);
  await page.getByRole('button', { name: 'Запланувати ремонт' }).click();
  await expect(page.getByText('За планом місце доступне на весь період.')).toBeVisible();
  await page.getByLabel('Тривалість у календарних днях').fill('10');
  await page.getByLabel('Орієнтовна вартість, ₴').fill('1200');
  await page.getByLabel('Підтверджую, що огляд проведено і умови погоджено').check();
  await expect(page.getByText('За планом місце доступне на весь період.')).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Підтвердити і запланувати' }).click();
  await expect(page.getByText('Ремонт заплановано.')).toBeVisible();
  await expect(page.getByText('Заплановано', { exact: true }).first()).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.goto('/admin/inspection-calendar');
  await page.getByRole('button', { name: 'Налаштування графіка' }).click();
  await expect(page.getByText(/Фактично у роботі:/)).toBeVisible();
  await page.getByText('Показати планову зайнятість за днями').click();
  await expect(page.getByText(/: 1 \/ 2/).first()).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
